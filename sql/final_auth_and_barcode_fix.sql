-- سياق الفني الحالي (محافظته، صلاحياته، توفره) بدون كشف أي فني آخر
create or replace function private.my_tech_ctx()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_tech public.technicians;
  v_perms jsonb;
begin
  select t.* into v_tech
    from public.technicians t
   where t.user_ref_id = private.my_user_id()
   order by t.id asc
   limit 1;

  if v_tech.id is null then
    return jsonb_build_object(
      'tech_id', null, 'name', null, 'phone', null, 'governorate', null,
      'all_governorates', false, 'is_available', false, 'is_active', false,
      'permissions', '{}'::jsonb, 'barcode_image', null
    );
  end if;

  v_perms := coalesce(v_tech.permissions, '{}'::jsonb);

  return jsonb_build_object(
    'tech_id',         v_tech.id,
    'name',            v_tech.name,
    'phone',           v_tech.phone,
    'governorate',     v_tech.governorate,
    'code',            v_tech.code,
    'specialty',       v_tech.specialty,
    'all_governorates', coalesce((v_perms->>'allGovernorates')::boolean, false),
    'view_orders',      coalesce((v_perms->>'viewOrders')::boolean, true),
    'update_status',    coalesce((v_perms->>'updateStatus')::boolean, true),
    'view_customer',    coalesce((v_perms->>'viewCustomer')::boolean, false),
    'is_available',     coalesce(v_tech.is_available, true),
    'is_active',        coalesce(v_tech.is_active, true),
    'permissions',      v_perms,
    'barcode_image',    v_tech.barcode_image
  );
end $$;

