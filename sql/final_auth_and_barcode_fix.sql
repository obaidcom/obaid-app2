-- ---------- 7.3 حالة الطلب: انتقالات صارمة بلا قفز عشوائي ----------
create or replace function public.validate_order_status_transition()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_allowed text[] := array[
    'pending>accepted', 'pending>assigned', 'pending>cancelled',
    'accepted>assigned', 'accepted>in-progress', 'accepted>cancelled',
    'assigned>in-progress', 'assigned>cancelled',
    'in-progress>completed', 'in-progress>cancelled',
    'completed>awaiting_payment', 'completed>pending_verification', 'completed>paid',
    'awaiting_payment>pending_verification', 'awaiting_payment>paid',
    'awaiting_payment>completed', 'awaiting_payment>overdue',
    'pending_verification>paid', 'pending_verification>awaiting_payment',
    'pending_verification>completed',
    'overdue>pending_verification', 'overdue>paid',
    'paid>completed'
  ];
  v_states text[] := array[
    'pending','accepted','assigned','in-progress','completed','cancelled',
    'awaiting_payment','pending_verification','paid','overdue'
  ];
begin
  if coalesce((select auth.role()), '') <> 'authenticated' then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if coalesce(new.status, 'pending') <> 'pending' then
      raise exception 'يجب أن يبدأ الطلب بحالة "تم استلام الطلب"' using errcode = '22023';
    end if;
    return new;
  end if;

  if new.status is not distinct from old.status then
    return new;
  end if;

  if not (new.status = any(v_states)) then
    raise exception 'حالة طلب غير معروفة: %', new.status using errcode = '22023';
  end if;

  if private.is_admin() then
    return new;
  end if;

  if not ((old.status || '>' || new.status) = any(v_allowed)) then
    raise exception 'انتقال حالة غير مسموح: % ← %', old.status, new.status using errcode = '42501';
  end if;
  return new;
end $$;

-- ---------- 7.4 حماية الطلبات: لا تعديل لطلب فني آخر ولا لحقول العميل ----------
create or replace function public.prevent_tech_order_tamper()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tech  bigint := private.my_tech_id();
  v_owner bigint := private.my_user_id();
begin
  if coalesce((select auth.role()), '') <> 'authenticated' then
    return new;                     -- service_role / SQL editor
  end if;
  if private.is_admin() then
    return new;
  end if;

  if new.id is distinct from old.id
     or new.user_id is distinct from old.user_id
     or new.created_at is distinct from old.created_at then
    raise exception 'لا يمكن تعديل هوية الطلب' using errcode = '42501';
  end if;

  -- (أ) العميل صاحب الطلب
  if v_owner is not null and old.user_id = v_owner then
    if new.tech_id is distinct from old.tech_id
       or new.accepted_by_tech is distinct from old.accepted_by_tech
       or new.tech_name is distinct from old.tech_name
       or new.tech_phone is distinct from old.tech_phone
       or new.tech_accepted_at is distinct from old.tech_accepted_at
       or new.on_the_way_at is distinct from old.on_the_way_at
       or new.started_at is distinct from old.started_at
       or new.invoice_id is distinct from old.invoice_id
       or new.invoice_number is distinct from old.invoice_number
       or new.invoice_amount is distinct from old.invoice_amount then
      raise exception 'لا يمكنك تعديل بيانات التنفيذ أو الفاتورة' using errcode = '42501';
    end if;

    if new.status is distinct from old.status then
      if new.status = 'cancelled' then
        if old.status in ('completed', 'awaiting_payment', 'pending_verification', 'paid', 'overdue') then
          raise exception 'لا يمكن إلغاء طلب تم تنفيذه' using errcode = '42501';
        end if;
      elsif new.status = 'pending_verification' then
        -- مسموح فقط عندما يكون العميل قد رفع إيصال الدفع فعلاً لفواتير هذا الطلب
        if not exists (
          select 1 from public.invoices i
           where i.order_id = old.id
             and i.receipt_status = 'pending_verification'
        ) then
          raise exception 'لا يمكن تغيير حالة الطلب إلى %', new.status using errcode = '42501';
        end if;
      else
        raise exception 'لا يمكن تغيير حالة الطلب إلى %', new.status using errcode = '42501';
      end if;
    end if;
    return new;
  end if;

  -- (ب) الفني المسؤول عن الطلب
  if v_tech is not null
     and (
       old.tech_id = v_tech
       or old.accepted_by_tech = v_tech
       or (coalesce(old.tech_id, old.accepted_by_tech) is null and new.tech_id = v_tech)
     ) then
    if new.name is distinct from old.name
       or new.phone is distinct from old.phone
       or new.service is distinct from old.service
       or new.date is distinct from old.date
       or new.time is distinct from old.time
       or new.governorate is distinct from old.governorate
       or new.user_id is distinct from old.user_id then
      raise exception 'لا يمكنك تعديل بيانات الطلب الأساسية' using errcode = '42501';
    end if;

    if coalesce(old.tech_id, old.accepted_by_tech) is not null
       and coalesce(old.tech_id, old.accepted_by_tech) is distinct from v_tech then
      raise exception 'هذا الطلب مسند إلى فني آخر' using errcode = '42501';
    end if;
    if coalesce(new.tech_id, new.accepted_by_tech) is distinct from v_tech then
      raise exception 'لا يمكنك فصل الطلب عنك' using errcode = '42501';
    end if;
    return new;
  end if;

  raise exception 'غير مسموح بتعديل هذا الطلب' using errcode = '42501';
end $$;

-- ---------- 7.5 حماية الفواتير: العميل لا يعدّل المبالغ، الفني لا يعدّل فاتورة غيره ----------
create or replace function public.prevent_tech_invoice_tamper()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tech  bigint := private.my_tech_id();
  v_user  bigint := private.my_user_id();
begin
  if coalesce((select auth.role()), '') <> 'authenticated' then
    return new;                     -- service_role / SQL editor
  end if;
  if private.is_admin() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if v_tech is null or new.tech_id is distinct from v_tech then
      raise exception 'لا يمكنك إنشاء فاتورة لطلب ليس لك' using errcode = '42501';
    end if;
    if new.customer_id is null then
      raise exception 'الفاتورة يجب أن ترتبط بعميل' using errcode = '42501';
    end if;
    return new;
  end if;

  if new.id is distinct from old.id or new.created_at is distinct from old.created_at then
    raise exception 'لا يمكن تعديل معرّف الفاتورة' using errcode = '42501';
  end if;

  -- (أ) العميل: الإيصال فقط
  if v_user is not null and old.customer_id = v_user then
