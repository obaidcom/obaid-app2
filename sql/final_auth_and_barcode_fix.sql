      raise exception 'لا يمكنك تعديل مبالغ الفاتورة أو تأكيد دفعها' using errcode = '42501';
    end if;
    if new.status not in (old.status, 'pending_verification') then
      raise exception 'لا يمكنك تغيير حالة الفاتورة' using errcode = '42501';
    end if;
    if new.receipt_status not in (old.receipt_status, 'pending_verification') then
      raise exception 'لا يمكنك تغيير حالة الإيصال' using errcode = '42501';
    end if;
    return new;
  end if;

  -- (ب) الفني المسؤول: التحقق من الإيصال فقط
  if v_tech is not null and old.tech_id = v_tech then
    if new.total is distinct from old.total
       or new.tax is distinct from old.tax
       or new.base_price is distinct from old.base_price
       or new.tech_id is distinct from old.tech_id
       or new.customer_id is distinct from old.customer_id
       or new.order_id is distinct from old.order_id
       or new.invoice_number is distinct from old.invoice_number
       or new.payment_barcode_image is distinct from old.payment_barcode_image
       or new.barcode_image is distinct from old.barcode_image
       or new.receipt_image is distinct from old.receipt_image then
      raise exception 'لا يمكنك تعديل بيانات الفاتورة الأساسية' using errcode = '42501';
    end if;
    if new.status not in (old.status, 'paid', 'awaiting_payment', 'pending_payment', 'pending_verification') then
      raise exception 'لا يمكنك تغيير حالة الفاتورة إلى %', new.status using errcode = '42501';
    end if;
    if new.receipt_status not in (old.receipt_status, 'pending_verification', 'verified', 'rejected') then
      raise exception 'لا يمكنك تغيير حالة الإيصال إلى %', new.receipt_status using errcode = '42501';
    end if;
    return new;
  end if;

  raise exception 'غير مسموح بتعديل هذه الفاتورة' using errcode = '42501';
end $$;

-- ---------- 7.6 تجميد باركود الدفع داخل الفاتورة وقت إنشائها ----------
--  القاعدة: باركود الفني أولاً ثم باركود الشركة، ويُنسخ داخل الفاتورة فلا
--  يتأثر بأي تغيير لاحق على باركود الفني أو إعدادات الشركة.
create or replace function public.freeze_invoice_barcode()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tech_id bigint;
  v_resolved text;
begin
  v_tech_id := coalesce(
    new.tech_id,
    (select o.tech_id from public.orders o where o.id = new.order_id)
  );

  if coalesce(trim(coalesce(new.payment_barcode_image, '')), '') = '' then
    v_resolved := private.resolve_payment_barcode(v_tech_id);
    new.payment_barcode_image := coalesce(v_resolved, nullif(trim(coalesce(new.barcode_image, '')), ''));
  end if;

  if coalesce(trim(coalesce(new.barcode_image, '')), '') = '' then
    new.barcode_image := new.payment_barcode_image;
  end if;

  return new;
end $$;

-- ---------- 7.7 تمرير إشعار الفني إلى جدول notifications (لمسار Push) ----------
create or replace function public.fanout_tech_notification_to_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id bigint;
begin
  if new.is_read is true then
    return new;                       -- إشعار داخلي مقروء: لا يستدعي Push
  end if;

  -- الإشعار يُوجَّه إلى صاحب حساب الفني نفسه (users.id) حتى يصل Push إلى جهازه
  select t.user_ref_id into v_user_id
    from public.technicians t
   where t.id = new.tech_id;

  if v_user_id is null then
    return new;
  end if;

  -- لا نُكرّر إشعاراً أضافه التطبيق مباشرة قبل لحظات
  if exists (
    select 1 from public.notifications n
     where n.user_id = v_user_id
       and n.related_id = new.order_id
       and n.message = new.message
       and n.created_at > now() - interval '90 seconds'
  ) then
    return new;
  end if;

  insert into public.notifications (user_id, title, message, type, related_id, order_id, is_read)
  values (v_user_id, 'طلب جديد', new.message,
          coalesce(new.type, 'tech_order'), new.order_id, new.order_id, false);

  return new;
end $$;

