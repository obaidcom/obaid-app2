-- ============================================================================
-- 2) الربط: كيف تُربط الحسابات القديمة بـ Supabase Auth؟
-- ============================================================================
--  المسار الرسمي (المستخدم نفسه، من داخل التطبيق):
--    1. المستخدم يفتح شاشة الدخول ويضغط "حساب قديم؟ رحّل حسابك".
--    2. يُدخل بريده وكلمة المروره القديمة + كلمة مرور جديدة (8 خانات وأكثر).
--    3. index.html ينشئ حساب Auth جديداً: sb.auth.signUp({email, password}).
--       - إن كان البريد مستخدماً مسبقاً في Auth، يُطلب منه تسجيل الدخول
--         ثم يُستأنف الترحيل تلقائياً بعد التأكد من مطابقة البريد.
--    4. index.html يستدعي Edge Function: migrate-legacy-users
--       مع Authorization: Bearer <access_token> الخاص بجلسة المستخدم.
--    5. Edge Function:
--       - يتأكد أن التوكن صالح وأن بريد الجلسة = البريد المطلوب ترحيله.
--       - يستدعي public.legacy_verify_password(email, old_password)
--         (service_role فقط) للتحقق من كلمة المرور القديمة.
--       - إن نجح التحقق: يستدعي legacy_mark_migrated(email, auth_uid, …)
--         الذي يربط الصف بالحساب الجديد ويمسح pass_word.
--       - يسجّل كل محاولة في legacy_migration_attempts.
--    6. المستخدم يصبح قادراً على الدخول ببريده وكلمة مروره الجديدة فقط.
--
--  المسار اليدوي (فقط للحالات التي تعذّر فيها التحقق الآلي):
--    الأدمن يفتح: لوحة التحكم → المستخدمون → "ربط حساب بـ Auth"
--    (دالة public.link_my_user_row للربط الذاتي، أو admin_set_user_role
--     لتصحيح الدور بعد الربط).
--    لا تُكتب أي كلمة مرور جديدة من جهة الأدمن إطلاقاً.


-- ============================================================================
-- 3) مصير users.pass_word
-- ============================================================================
--  | المرحلة                     | حالة pass_word                              |
--  |----------------------------|---------------------------------------------|
--  | قبل الترحيل                 | نص صريح قديم — للتحقق مرة واحدة فقط         |
--  | أثناء الترحيل الناجح        | يُضبط إلى NULL داخل legacy_mark_migrated    |
--  | بعد الترحيل                 | NULL دائماً، ولا يُكتب مرة أخرى إطلاقاً      |
--  | حساب لا يستطيع إثبات الملكية| يبقى كما هو (لا يُمس) ولا يُربط             |
--
--  سبب الإبقاء المؤقت: لا يمكن التحقق من صحة كلمة المرور القديمة بدونها،
--  لأنها مخزّنة كنص صريح (وليست bcrypt). بعد نجاح الترحيل لا قيمة لها.
--
--  بعد اكتمال كل عمليات الترحيل المطلوبة، تُشطب نهائياً على مستوى النظام:
--    update public.users set pass_word = null where pass_word is not null;   -- (يدوياً مرة واحدة بعد المراجعة)
--    alter table public.users drop column pass_word;                          -- (اختياري، بعد التأكد من عدم وجود أي اعتماد)


-- ============================================================================
-- 4) المستخدمون الذين لا يستطيعون إثبات ملكية كلمة المرور القديمة
-- ============================================================================
--  الحالات المحتملة:
--    أ) نسي كلمة المرور القديمة → لا يمكن الترحيل الآلي.
--       الحل: إنشاء حساب جديد بنفس البريد عبر signUp()، ثم يثبت ملكية البريد
--       (تأكيد البريد أو مطابقة رقم الهاتف)، ثم يربط الأدمن صفّه القديم
--       بالحساب الجديد مع الحفاظ على الدور والطلبات والفواتير.
--    ب) الحساب القديم بلا بريد إلكتروني → لا يمكن ترحيله إطلاقاً.
--       الحل: يبقى الصف التاريخي للقراءة فقط، ويُنشئ المستخدم حساباً جديداً.
--       تُطلب منه بيانات مطابقة (الاسم + الهاتف) لتأكيد ملكية الطلبات القديمة
--       قبل ربطها يدوياً بواسطة الأدمن.
--    ج) كلمة المرور القديمة لا تُطابق النص المخزّن (تعديل مباشر في القاعدة).
--       الحل: نفس مسار (أ).
--  في جميع الحالات: لا يُحذف الحساب القديم، ولا تُفقد الطلبات أو الفواتير،
--  ويُسجَّل كل فشل في legacy_migration_attempts للمراجعة الأمنية.


-- ============================================================================
-- 5) منع ازدواج الحسابات (Duplicate-Account Prevention)
-- ============================================================================
--  5.1 على مستوى قاعدة البيانات:
--      - فهرس فريد على users.auth_uid يمنع ربط حسابَي Auth بالصف نفسه.
--      - فهرس فريد على lower(trim(users.email)) يمنع إنشاء صفّين لنفس البريد
--        (متى ما طُبِّق بعد تنظيف الازدواجات في الفقرة 1.4).
--      - legacy_mark_migrated يرفض (ALREADY_MIGRATED) أي محاولة لربط صفّ
--        مرتبط مسبقاً بـ auth_uid مختلف، حتى لو كان البريد واحداً.
--  5.2 على مستوى Edge Function:
--      - يستخرج auth_uid من توكن الجلسة فقط (لا يقبله من جسم الطلب).
--      - يقارن بريد الجلسة ببريد الطلب (يجب التطابق التام).
--      - يمنع ترحيل حساب يخص شخصاً آخر (لا يمكن تمرير بريد غير بريدك).
--      - يعيد أخطاء عامة للمستخدم ويسجّل التفاصيل داخلياً فقط.
--  5.3 على مستوى التطبيق:
--      - signUp يُعاد له "بريد مسجّل مسبقاً" من Supabase Auth فينتقل تلقائياً
--        إلى مسار تسجيل الدخول بدل إنشاء حساب ثانٍ.
--      - بعد الدخول، البحث عن صف users يتم بـ auth_uid فقط (لا بالبريد وحده).
--
--  خطوات التنظيف اليدوية قبل تشغيل الترحيل على بيانات حقيقية:
--    1) راجع نتيجة 1.4 (ازدواج البريد) وأبقِ الصف الأقدم (keep_id) دائماً.
--    2) راجع 1.3 (بلا بريد) وأكمل بياناتهم بالهاتف قبل أي ترحيل.
--    3) شغّل sql/final_auth_and_barcode_fix.sql (ينشئ الفهارس الفريدة محميّة).
--    4) نفّذ ترحيل حساب اختباري واحد من داخل التطبيق، وتأكد من:
--         - اختفاء pass_word من الصف
--         - ظهور auth_uid
--         - القدرة على الدخول بالبريد وكلمة المرور الجديدة فقط
--    5) بعد نجاح الاختبار، أبلغ المستخدمين القدامى بالمسار الجديد.


-- ============================================================================
-- 6) استعلام المراقبة بعد الترحيل (بلا تعديل)
-- ============================================================================
-- 6.1 كم بقي؟ / كم رُحّل؟
select (select count(*) from public.users where auth_uid is not null)  as migrated,
       (select count(*) from public.users where auth_uid is null)      as pending;

-- 6.2 آخر محاولات الترحيل (نجاح/فشل + السبب)
select email, success, reason, created_at
  from public.legacy_migration_attempts
 order by id desc
 limit 50;

-- 6.3 محاولات فاشلة متكررة على البريد نفسه (مؤشر محاولة اختراق)
select email, count(*) as failures, max(created_at) as last_try
  from public.legacy_migration_attempts
 where success = false
 group by 1
having count(*) >= 5
 order by 2 desc;

