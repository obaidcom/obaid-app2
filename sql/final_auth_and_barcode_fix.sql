-- ---------- 8.1 ربط حساب Auth بصف users (بالبريد المطابق فقط) ----------
create or replace function public.link_my_user_row(p_name text default null, p_phone text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid   uuid := (select auth.uid());
  v_email text := lower(trim(coalesce((select auth.jwt()) ->> 'email', '')));
  v_row   public.users;
  v_role  text := 'user';
  v_new   boolean := false;
begin
  if v_uid is null then
    raise exception 'يجب تسجيل الدخول أولاً' using errcode = '42501';
  end if;

  select * into v_row from public.users u where u.auth_uid = v_uid order by u.id asc limit 1;
  if v_row.id is not null then
    return jsonb_build_object('ok', true, 'created', false, 'user', to_jsonb(v_row) - 'pass_word');
  end if;

  if v_email <> '' then
    select * into v_row from public.users u
     where lower(trim(coalesce(u.email, ''))) = v_email order by u.id asc limit 1;

    if v_row.id is not null then
      if v_row.auth_uid is not null and v_row.auth_uid <> v_uid then
        raise exception 'هذا البريد مرتبط بحساب آخر' using errcode = '42501';
      end if;
      -- حساب قديم لا يزال يعتمد على كلمة مرور نصية → لا يُربط بالبريد فقط،
      -- بل يجب إثبات كلمة المرور القديمة عبر مسار "ترحيل حساب قديم" (Edge Function).
      if v_row.pass_word is not null and length(trim(v_row.pass_word)) > 0 then
        raise exception 'هذا حساب قديم — استخدم "ترحيل حساب قديم" لإثبات كلمة المرور القديمة وربط الحساب'
          using errcode = '42501';
      end if;
      update public.users
         set auth_uid = v_uid,
             name     = coalesce(nullif(trim(coalesce(v_row.name, '')), ''), nullif(trim(coalesce(p_name, '')), ''), name),
             phone    = coalesce(nullif(trim(coalesce(v_row.phone, '')), ''), nullif(trim(coalesce(p_phone, '')), ''), phone),
             updated_at = now()
       where id = v_row.id
       returning * into v_row;
      return jsonb_build_object('ok', true, 'created', false, 'user', to_jsonb(v_row) - 'pass_word');
    end if;
  end if;

  -- الأدمن يُمنح فقط لمن يملك دعوة أدمن أو حساباً في جدول admins القديم المفعّل
  if v_email <> '' then
    if to_regclass('public.admin_invites') is not null
       and exists (select 1 from public.admin_invites i where lower(trim(coalesce(i.email, ''))) = v_email) then
      v_role := 'admin';
    elsif private.legacy_admin_email_exists(v_email) then
      v_role := 'admin';
    end if;
  end if;

  insert into public.users (name, email, phone, role, auth_uid)
  values (
    coalesce(nullif(trim(coalesce(p_name, '')), ''), split_part(v_email, '@', 1), 'مستخدم'),
    v_email,
    coalesce(p_phone, ''),
    v_role,
    v_uid
  )
  returning * into v_row;

  v_new := true;
  return jsonb_build_object('ok', true, 'created', v_new, 'user', to_jsonb(v_row) - 'pass_word');
end $$;

-- ---------- 8.2 ملفّي: المستخدم + سجل الفني (إن وُجد) ----------
create or replace function public.my_profile()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_uid   uuid := (select auth.uid());
  v_user  jsonb;
  v_tech  jsonb;
  v_role  text;
  v_techid bigint;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'reason', 'not_authenticated', 'user', null, 'technician', null);
  end if;

  select to_jsonb(u) - 'pass_word' into v_user
    from public.users u
   where u.auth_uid = v_uid
   order by u.id asc
   limit 1;

  if v_user is null then
    return jsonb_build_object('ok', true, 'needs_link', true, 'user', null, 'technician', null, 'is_admin', false);
  end if;

  v_role   := coalesce(v_user ->> 'role', 'user');
  v_techid := private.my_tech_id();

  if v_techid is not null then
    select to_jsonb(t) into v_tech
      from public.technicians t
     where t.id = v_techid;
  end if;

  return jsonb_build_object(
    'ok',         true,
    'needs_link', false,
    'user',       v_user,
    'role',       v_role,
    'is_admin',   v_role = 'admin',
