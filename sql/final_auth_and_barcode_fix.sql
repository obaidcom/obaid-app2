-- ---------- 7.1 منع رفع الدور / تغيير الهوية / تخزين كلمة مرور نصية ----------
create or replace function public.prevent_user_privilege_escalation()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce((select auth.role()), '') <> 'authenticated' then
    return new;                     -- service_role / SQL editor
  end if;
  if private.is_admin() then
    return new;
  end if;

  if tg_op = 'INSERT' then
    if coalesce(new.role, 'user') <> 'user' then
      -- الاستثناء الوحيد: دعوة أدمن/فني مسجّلة مسبقاً لنفس البريد (يديرها المشرف)
      if not (
        new.email is not null
        and coalesce(trim(new.email), '') <> ''
        and (
          (
            to_regclass('public.admin_invites') is not null
            and exists (
              select 1 from public.admin_invites i
               where lower(trim(coalesce(i.email, ''))) = lower(trim(new.email))
                 and coalesce(i.role, 'admin') = new.role
            )
          )
          or (
            new.role = 'admin'
            and private.legacy_admin_email_exists(new.email)
          )
        )
      ) then
        raise exception 'لا يمكن إنشاء حساب بدور %', new.role using errcode = '42501';
      end if;
    end if;
    if new.auth_uid is not null and new.auth_uid <> (select auth.uid()) then
      raise exception 'لا يمكن ربط الحساب بهوية حساب آخر' using errcode = '42501';
    end if;
    if new.pass_word is not null and length(trim(new.pass_word)) > 0 then
      raise exception 'لا يُسمح بتخزين كلمة مرور نصية — استخدم Supabase Auth' using errcode = '42501';
    end if;
    if new.is_active is false then
      raise exception 'لا يمكن إنشاء حساب معطّل' using errcode = '42501';
    end if;
    return new;
  end if;

  -- UPDATE
  if new.id is distinct from old.id then
    raise exception 'لا يمكن تعديل معرّف الحساب' using errcode = '42501';
  end if;
  if new.role is distinct from old.role then
    raise exception 'لا يمكنك تغيير دورك — تُرقّي الحسابات بواسطة المشرف فقط' using errcode = '42501';
  end if;
  if new.is_active is distinct from old.is_active then
    raise exception 'تعديل حالة الحساب من صلاحيات المشرف' using errcode = '42501';
  end if;
  if new.auth_uid is distinct from old.auth_uid then
    if not (old.auth_uid is null and new.auth_uid = (select auth.uid())) then
      raise exception 'لا يمكن تغيير ربط الحساب بعد إنشائه' using errcode = '42501';
    end if;
  end if;
  if new.pass_word is not null and length(trim(new.pass_word)) > 0 then
    raise exception 'لا يُسمح بتخزين كلمة مرور نصية — استخدم Supabase Auth' using errcode = '42501';
  end if;
  return new;
end $$;

