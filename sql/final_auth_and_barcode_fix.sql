-- باركود الشركة المخزّن في settings(key='barcode') — آمن مع text أو jsonb
create or replace function private.company_barcode()
returns text
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_raw text;
  v_img text;
begin
  select s.value::text into v_raw
    from public.settings s
   where s.key = 'barcode'
   order by s.updated_at desc nulls last
   limit 1;

  if v_raw is null or length(trim(v_raw)) = 0 then
    return null;
  end if;

  begin
    v_img := (v_raw::jsonb) ->> 'image';
  exception when others then
    v_img := null;
  end;

  return nullif(trim(coalesce(v_img, v_raw)), '');
end $$;

