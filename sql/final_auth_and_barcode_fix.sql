-- 10.2 تطبيع حالات الطلبات القديمة
update public.orders set status = 'pending'     where status is null or lower(trim(status)) in ('new','received','قيد الانتظار');
update public.orders set status = 'accepted'    where lower(trim(status)) in ('accepted_by_admin');
update public.orders set status = 'in-progress' where lower(trim(status)) in ('processing','in_progress','ongoing','working');
update public.orders set status = 'completed'   where lower(trim(status)) in ('done','finished','ended');
update public.orders set status = 'cancelled'   where lower(trim(status)) in ('canceled','rejected');
update public.orders set status = 'in-progress' where lower(trim(status)) not in
  ('pending','accepted','assigned','in-progress','completed','cancelled','awaiting_payment','pending_verification','paid','overdue');

-- 10.3 توحيد tech_id و accepted_by_tech في الطلبات
update public.orders set accepted_by_tech = tech_id
 where accepted_by_tech is null and tech_id is not null and coalesce(trim(status), '') <> 'pending';
update public.orders set tech_id = accepted_by_tech
 where tech_id is null and accepted_by_tech is not null;

update public.orders o
   set tech_name  = coalesce(nullif(trim(coalesce(o.tech_name, '')), ''), t.name),
       tech_phone = coalesce(nullif(trim(coalesce(o.tech_phone, '')), ''), t.phone)
  from public.technicians t
 where o.tech_name is null
   and t.id = coalesce(o.tech_id, o.accepted_by_tech);

-- 10.4 ربط الفواتير القديمة بالفني وبالباركود
update public.invoices i
   set tech_id = coalesce(o.tech_id, o.accepted_by_tech)
  from public.orders o
 where i.order_id = o.id
   and i.tech_id is null
   and coalesce(o.tech_id, o.accepted_by_tech) is not null;

update public.invoices
   set payment_barcode_image = barcode_image
 where payment_barcode_image is null
   and coalesce(trim(coalesce(barcode_image, '')), '') <> '';

update public.invoices set receipt_status = 'none'   where receipt_status is null or lower(trim(receipt_status)) = '';
update public.invoices set receipt_status = 'pending_verification'
 where receipt_image is not null and receipt_status = 'none';
update public.invoices set status = 'awaiting_payment'
 where status is null or lower(trim(status)) in ('unpaid','not_paid','open');
update public.invoices set status = 'pending_verification'
 where lower(trim(status)) in ('review','verifying','waiting_verification');
update public.invoices set status = 'paid'
 where lower(trim(status)) in ('confirmed','verified','settled');
update public.invoices set status = 'pending_payment'
 where lower(trim(status)) not in ('pending_payment','pending_verification','paid','overdue','cancelled','awaiting_payment');

