grant usage on schema private to authenticated, service_role;

-- دالة مساعدة عامة: هل الجلسة الحالية هي المفتاح الخدمي (service_role)؟
-- تُستخدم داخل Triggers للسماح لـ Edge Functions بالعمل (service_role يتجاوز RLS
-- لكنه لا يتجاوز Triggers، لذا نحتاج هذا الفحص).
create or replace function private.is_service_role()
returns boolean
language sql
stable
as $$
  select coalesce((select auth.role()), '') = 'service_role'
$$;

revoke all on function private.is_service_role() from public, anon, authenticated;
grant execute on function private.is_service_role() to authenticated, service_role;

