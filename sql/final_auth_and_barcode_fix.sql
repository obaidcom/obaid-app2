-- ---------- 8.13 إنشاء الفاتورة (مرتبطة بالفني + تجميد الباركود + إشعار) ----------
create or replace function public.create_invoice_for_order(
  p_order_id         bigint,
  p_base_price       numeric default 0,
  p_tax              numeric default 0,
  p_total            numeric default null,
  p_notes            text    default null,
  p_service          text    default null,
  p_customer_name    text    default null,
  p_customer_phone   text    default null,
  p_customer_email   text    default null,
  p_fallback_barcode text    default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_role      text := private.my_role();
  v_my_tech   bigint := private.my_tech_id();
  v_order     public.orders;
  v_inv       public.invoices;
  v_tech_id   bigint;
  v_base      numeric;
  v_tax       numeric;
  v_total     numeric;
  v_barcode   text;
  v_number    text;
begin
  select * into v_order from public.orders o where o.id = p_order_id for update;
  if v_order.id is null then
    raise exception 'الطلب غير موجود' using errcode = 'P0002';
  end if;

  -- (1) من المسؤول عن الفاتورة؟
  if private.is_admin() then
    v_tech_id := coalesce(v_order.tech_id, v_order.accepted_by_tech);
  elsif v_role = 'technician' then
    v_tech_id := coalesce(v_order.tech_id, v_order.accepted_by_tech);
    if v_tech_id is null or v_tech_id <> v_my_tech then
      raise exception 'لا يمكنك إنشاء فاتورة لطلب ليس لك' using errcode = '42501';
    end if;
    -- التسلسل الإلزامي: تم الانتهاء أولاً ثم تصدر الفاتورة
    if v_order.status <> 'completed' then
      raise exception 'يجب إنهاء الخدمة أولاً (تم الانتهاء) قبل إنشاء الفاتورة — الحالة الحالية: %', v_order.status
        using errcode = '42501';
    end if;
  else
    raise exception 'غير مسموح بإنشاء الفواتير' using errcode = '42501';
  end if;

  -- (2) لا فاتورتان لنفس الطلب
  select * into v_inv from public.invoices i where i.order_id = v_order.id order by i.id asc limit 1;
  if v_inv.id is not null then
    return jsonb_build_object('ok', true, 'existing', true, 'invoice', to_jsonb(v_inv));
  end if;

  v_base  := greatest(coalesce(p_base_price, 0), 0);
  v_tax   := greatest(coalesce(p_tax, 0), 0);
  v_total := greatest(coalesce(p_total, v_base + v_tax), 0);

  -- (3) الباركود: باركود الفني أولاً ثم باركود الشركة ثم البديل المُمرَّر
  v_barcode := coalesce(
    private.resolve_payment_barcode(v_tech_id),
    nullif(trim(coalesce(p_fallback_barcode, '')), '')
  );

  v_number := 'INV-' || to_char(now(), 'YYYYMMDD-HH24MISS') || '-'
              || lpad((floor(random() * 9000) + 1000)::int::text, 4, '0');

  insert into public.invoices (
    order_id, invoice_number, customer_id, customer_name, customer_email, customer_phone,
    tech_id, service, service_date, base_price, tax, total, status, notes,
    payment_barcode_image, barcode_image, receipt_status, sent_at
  ) values (
    v_order.id,
    v_number,
    v_order.user_id,
    coalesce(nullif(trim(coalesce(p_customer_name, '')), ''), v_order.name, 'عميل'),
    coalesce(p_customer_email, ''),
    coalesce(nullif(trim(coalesce(p_customer_phone, '')), ''), v_order.phone, ''),
    v_tech_id,
    coalesce(nullif(trim(coalesce(p_service, '')), ''), v_order.service, 'خدمة صيانة'),
    coalesce(v_order.date, ''),
    v_base,
    v_tax,
    v_total,
    'pending_payment',
    coalesce(p_notes, 'فاتورة عن خدمة ' || coalesce(v_order.service, '')),
    v_barcode,
    v_barcode,
    'none',
    now()
  )
  returning * into v_inv;

  update public.orders
     set invoice_id     = v_inv.id,
         invoice_number = v_inv.invoice_number,
         invoice_amount = v_inv.total,
         status         = 'awaiting_payment',
         updated_at     = now()
   where id = v_order.id
   returning * into v_order;

  perform private.push_notification(
    v_order.user_id, 'فاتورة جديدة',
    '🧾 صدرت فاتورة طلبك (' || coalesce(v_inv.service, '') || ') بمبلغ ' || to_char(coalesce(v_inv.total, 0), 'FM999999990.00') || ' — بانتظار الدفع',
    'new_invoice', v_inv.id, v_order.id, v_inv.id
  );

  return jsonb_build_object('ok', true, 'existing', false, 'invoice', to_jsonb(v_inv));
end $$;

