  v_tech   bigint := private.my_tech_id();
  v_img    text := nullif(trim(coalesce(p_receipt_image, '')), '');
  v_admin  record;
begin
  if v_img is null then
    raise exception 'صورة الإيصال مطلوبة' using errcode = '22023';
  end if;
  if length(v_img) > 5242880 then
    raise exception 'حجم صورة الإيصال كبير جداً (الحد 5 ميغابايت)' using errcode = '22023';
  end if;
  if v_img !~ '^data:image/' then
    raise exception 'صيغة صورة الإيصال غير مدعومة' using errcode = '22023';
  end if;

  select * into v_inv from public.invoices i where i.id = p_invoice_id for update;
  if v_inv.id is null then
    raise exception 'الفاتورة غير موجودة' using errcode = 'P0002';
  end if;

  if not (
    private.is_admin()
    or (v_user is not null and v_inv.customer_id = v_user)
    or (v_tech is not null and v_inv.tech_id = v_tech)
  ) then
    raise exception 'غير مسموح برفع إيصال لهذه الفاتورة' using errcode = '42501';
  end if;

  if v_inv.status = 'paid' then
    raise exception 'هذه الفاتورة مدفوعة ومؤكدة مسبقاً' using errcode = '22023';
  end if;

  update public.invoices
     set receipt_image  = v_img,
         receipt_status = 'pending_verification',
         status         = 'pending_verification',
         updated_at     = now()
   where id = v_inv.id
   returning * into v_inv;

  -- الطلب ينتقل إلى "جاري التحقق من الدفع"
  select * into v_order from public.orders o where o.id = v_inv.order_id for update;
  if v_order.id is not null
     and v_order.status in ('completed', 'awaiting_payment', 'overdue', 'pending_verification') then
    update public.orders
       set status = 'pending_verification', updated_at = now()
     where id = v_order.id
     returning * into v_order;
  end if;

  -- إشعار العميل باستلام الإيصال
  perform private.push_notification(
    v_inv.customer_id, 'تم استلام إيصالك',
    '📩 تم استلام إيصال الدفع وسيتم التحقق منه قريباً — الفاتورة ' || coalesce(v_inv.invoice_number, ''),
    'payment_review', v_inv.id, v_inv.order_id, v_inv.id
  );

  -- إشعار كل المشرفين للتحقق
  for v_admin in
    select u.id from public.users u
     where u.role = 'admin' and coalesce(u.is_active, true)
       and u.id <> coalesce(v_inv.customer_id, 0)
  loop
    perform private.push_notification(
      v_admin.id, 'إيصال دفع بانتظار التحقق',
      '💳 العميل ' || coalesce(v_inv.customer_name, '') || ' رفع إيصالاً للفاتورة '
        || coalesce(v_inv.invoice_number, '') || ' بمبلغ ' || to_char(coalesce(v_inv.total, 0), 'FM999999990.00'),
      'payment_uploaded', v_inv.id, v_inv.order_id, v_inv.id
    );
  end loop;

  -- إشعار الفني المسؤول
  if v_inv.tech_id is not null then
    insert into public.tech_notifications (tech_id, order_id, message, type, is_read)
    values (v_inv.tech_id, v_inv.order_id,
            'رفع العميل إيصال دفع للفاتورة ' || coalesce(v_inv.invoice_number, '') || ' بانتظار تأكيدك',
            'payment_received', false);
  end if;

  return to_jsonb(v_inv);
end $$;

-- ---------- 8.15 تأكيد / رفض الدفع ----------
create or replace function public.verify_invoice_receipt(
  p_invoice_id bigint,
  p_approve boolean,
  p_rejection_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_inv   public.invoices;
  v_order public.orders;
  v_tech  bigint := private.my_tech_id();
begin
  select * into v_inv from public.invoices i where i.id = p_invoice_id for update;
  if v_inv.id is null then
    raise exception 'الفاتورة غير موجودة' using errcode = 'P0002';
  end if;

  if not (private.is_admin() or (v_tech is not null and v_inv.tech_id = v_tech)) then
    raise exception 'غير مسموح بتأكيد دفع هذه الفاتورة' using errcode = '42501';
  end if;

  if coalesce(p_approve, false) then
    update public.invoices
       set status              = 'paid',
           receipt_status      = 'verified',
           receipt_verified_at = now(),
           rejection_reason    = null,
           updated_at          = now()
     where id = v_inv.id
     returning * into v_inv;

    select * into v_order from public.orders o where o.id = v_inv.order_id for update;
    if v_order.id is not null and v_order.status <> 'completed' then
      update public.orders
         set status = 'completed', updated_at = now()
       where id = v_order.id
       returning * into v_order;
    end if;

    perform private.push_notification(
      v_inv.customer_id, 'تم تأكيد الدفع',
      '✅ تم تأكيد دفع الفاتورة ' || coalesce(v_inv.invoice_number, '') || ' — شكراً لك',
      'payment_confirmed', v_inv.id, v_inv.order_id, v_inv.id
    );
  else
    if coalesce(trim(coalesce(p_rejection_reason, '')), '') = '' then
      raise exception 'سبب رفض الإيصال مطلوب' using errcode = '22023';
    end if;

    update public.invoices
       set status           = 'pending_payment',
           receipt_status   = 'rejected',
           rejection_reason = left(p_rejection_reason, 500),
           updated_at       = now()
     where id = v_inv.id
     returning * into v_inv;

    select * into v_order from public.orders o where o.id = v_inv.order_id for update;
    if v_order.id is not null and v_order.status <> 'cancelled' then
      update public.orders
         set status = 'awaiting_payment', updated_at = now()
       where id = v_order.id
       returning * into v_order;
    end if;

    perform private.push_notification(
      v_inv.customer_id, 'تم رفض إيصال الدفع',
      '❌ لم يتم تأكيد إيصال الفاتورة ' || coalesce(v_inv.invoice_number, '') || ' — السبب: ' || left(p_rejection_reason, 300),
      'payment_rejected', v_inv.id, v_inv.order_id, v_inv.id
    );
  end if;

  return to_jsonb(v_inv);
end $$;

-- ---------- 8.16 الأدمن: تغيير دور مستخدم ----------
create or replace function public.admin_set_user_role(p_user_email text, p_role text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(trim(coalesce(p_user_email, '')));
  v_role  text := lower(trim(coalesce(p_role, '')));
  v_user  public.users;
  v_admins int;
begin
  perform private.assert_admin();

  if v_email = '' then
    raise exception 'البريد الإلكتروني مطلوب' using errcode = '22023';
  end if;
  if v_role not in ('user', 'technician', 'admin') then
    raise exception 'دور غير معروف: %', p_role using errcode = '22023';
  end if;

  select * into v_user from public.users u where lower(trim(coalesce(u.email, ''))) = v_email order by u.id asc limit 1;
  if v_user.id is null then
    raise exception 'لا يوجد مستخدم بهذا البريد' using errcode = 'P0002';
  end if;

  if v_user.role = 'admin' and v_role <> 'admin' then
    select count(*) into v_admins from public.users u
     where u.role = 'admin' and coalesce(u.is_active, true) and u.id <> v_user.id;
    if v_admins = 0 then
      raise exception 'لا يمكن إزالة آخر مشرف مفعّل في النظام' using errcode = '42501';
    end if;
  end if;

  update public.users set role = v_role, updated_at = now() where id = v_user.id returning * into v_user;

  perform private.push_notification(
    v_user.id, 'تحديث صلاحيات الحساب',
    'تم تحديث دور حسابك إلى: ' || v_role,
    'role_changed', null, null, null
  );

  return jsonb_build_object('ok', true, 'user', to_jsonb(v_user) - 'pass_word');
end $$;

