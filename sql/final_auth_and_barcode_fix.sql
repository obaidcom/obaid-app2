-- ============================================================================
-- 4) تنظيف السياسات القديمة + تفعيل RLS على كل الجداول الحساسة
--    (حذف ديناميكي بكل الأسماء: لا نفترض أسماء السياسات القديمة)
-- ============================================================================
do $$
declare
  r record;
  t text;
  targets text[] := array[
    'users','technicians','orders','invoices','notifications','tech_notifications',
    'settings','push_subscriptions','discount_codes','complaints','ratings',
    'admin_invites','legacy_migration_attempts','admins'
  ];
begin
  for r in
    select schemaname, tablename, policyname
      from pg_policies
     where schemaname = 'public'
       and tablename = any(targets)
  loop
    execute format('drop policy if exists %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;

  foreach t in array targets loop
    if to_regclass('public.' || t) is not null then
      -- تفعيل RLS على كل جدول حساس
      execute format('alter table public.%I enable row level security', t);
    end if;
  end loop;
end $$;

