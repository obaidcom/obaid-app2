-- 8.22 دوال الترحيل الآمن للحسابات القديمة (service_role فقط)
--      تُستدعى حصرياً من Edge Function: supabase-functions/migrate-legacy-users
--      لا يستطيع أي عميل (anon/authenticated) تنفيذها إطلاقاً.
-- ============================================================================
create or replace function private.password_matches(p_stored text, p_plain text)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_stored text := coalesce(p_stored, '');
  v_ok     boolean := false;
begin
  if coalesce(p_plain, '') = '' or v_stored = '' then
    return false;
  end if;

  -- 1) نص صريح (الوضع القديم)
  if v_stored = p_plain then
    return true;
  end if;

  -- 2) bcrypt (إن كان pgcrypto متاحاً)
  if v_stored ~ '^\$2[aby]?\$' then
    begin
      execute 'select crypt($1, $2) = $2' into v_ok using p_plain, v_stored;
      if v_ok then
        return true;
      end if;
    exception when others then
      null;                          -- pgcrypto غير متاح
    end;
  end if;

  -- 3) sha256 hex
  begin
    execute 'select encode(digest($1, ''sha256''), ''hex'')' into v_stored using p_plain;
    if lower(v_stored) = lower(coalesce(p_stored, '')) then
      return true;
    end if;
  exception when others then
    null;
  end;

  return false;
end $$;

revoke all on function private.password_matches(text, text) from public, anon, authenticated;

create or replace function public.legacy_verify_password(p_email text, p_password text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
  v_row   public.users;
  v_admin record;
begin
  if v_email = '' or p_password is null then
    return jsonb_build_object('ok', false, 'reason', 'invalid_request');
  end if;

  -- 1) مستخدم قديم في users: كلمة مرور نصية وبلا ربط Auth
  select * into v_row
    from public.users u
   where lower(trim(coalesce(u.email, ''))) = v_email
     and u.pass_word is not null
     and u.auth_uid is null
   order by u.id asc
   limit 1;

  if v_row.id is not null and private.password_matches(v_row.pass_word, p_password) then
    return jsonb_build_object(
      'ok', true, 'source', 'users', 'user_id', v_row.id,
      'role', coalesce(v_row.role, 'user'), 'name', v_row.name, 'phone', v_row.phone
    );
  end if;

  -- 2) مشرف قديم في جدول admins
  if to_regclass('public.admins') is not null then
    begin
      execute 'select id, name, email, password, role, is_active from public.admins where lower(email) = $1 limit 1'
        into v_admin using v_email;
      if v_admin.id is not null
         and coalesce(v_admin.is_active, true)
         and private.password_matches(v_admin.password, p_password) then
        return jsonb_build_object(
          'ok', true, 'source', 'admins', 'admin_id', v_admin.id,
          'role', coalesce(v_admin.role, 'admin'), 'name', v_admin.name, 'phone', null
        );
      end if;
    exception when others then
      null;
    end;
  end if;

  -- 3) هل الحساب مرتبط أصلاً بـSupabase Auth؟ (الربط الفعلي فقط)
  if exists (
    select 1 from public.users u
     where lower(trim(coalesce(u.email, ''))) = v_email
       and u.auth_uid is not null
  ) then
    return jsonb_build_object('ok', false, 'reason', 'already_migrated');
  end if;

  return jsonb_build_object('ok', false, 'reason', 'invalid_credentials');
end $$;

revoke all on function public.legacy_verify_password(text, text) from public, anon, authenticated;
grant execute on function public.legacy_verify_password(text, text) to service_role;

create or replace function public.legacy_mark_migrated(
  p_email text,
  p_auth_uid uuid,
  p_name text default null,
  p_phone text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_email text := lower(trim(coalesce(p_email, '')));
  v_row   public.users;
  v_role  text := 'user';
begin
  if v_email = '' or p_auth_uid is null then
    raise exception 'request_invalid' using errcode = '22023';
  end if;

  select * into v_row
    from public.users u
   where lower(trim(coalesce(u.email, ''))) = v_email
   order by u.id asc
   limit 1;

  if v_row.id is not null then
    if v_row.auth_uid is not null and v_row.auth_uid <> p_auth_uid then
      raise exception 'ALREADY_MIGRATED' using errcode = 'P0001';
    end if;
    update public.users
       set auth_uid   = p_auth_uid,
           pass_word  = null,
           name       = coalesce(nullif(trim(coalesce(v_row.name, '')), ''), nullif(trim(coalesce(p_name, '')), ''), name),
           phone      = coalesce(nullif(trim(coalesce(v_row.phone, '')), ''), nullif(trim(coalesce(p_phone, '')), ''), phone),
           updated_at = now()
     where id = v_row.id
     returning * into v_row;
  else
    if private.legacy_admin_email_exists(v_email) then
      v_role := 'admin';
    end if;
    insert into public.users (name, email, phone, role, auth_uid, pass_word)
    values (
      coalesce(nullif(trim(coalesce(p_name, '')), ''), 'مستخدم'),
      v_email,
      coalesce(p_phone, ''),
      v_role,
      p_auth_uid,
      null
    )
    returning * into v_row;
  end if;

  -- تنظيف كلمة المرور النصية في جدول admins القديم إن وُجد
  if to_regclass('public.admins') is not null then
    begin
      execute 'update public.admins set password = null where lower(email) = $1' using v_email;
    exception when others then null;
    end;
  end if;

  insert into public.legacy_migration_attempts (email, success, reason)
  values (v_email, true, 'migrated');

  return to_jsonb(v_row) - 'pass_word';
end $$;

revoke all on function public.legacy_mark_migrated(text, uuid, text, text) from public, anon, authenticated;
grant execute on function public.legacy_mark_migrated(text, uuid, text, text) to service_role;

