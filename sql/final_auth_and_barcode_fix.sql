-- ============================================================================
--  عبيد للصيانة — الملف النهائي الموحّد: مصادقة حقيقية + RLS صارم + باركود دفع
-- ============================================================================
--  اسم الملف: sql/final_auth_and_barcode_fix.sql
--  النوع: ملف واحد شامل (idempotent) — يمكن تنفيذه أكثر من مرة بدون أخطاء.
--  مكان التنفيذ: Supabase Dashboard → SQL Editor → Run  (كامل الملف مرة واحدة)
--
--  ما الذي يفعله؟
--    1) يبني/يكمل الجداول والأعمدة المطلوبة (بدون حذف أي بيانات موجودة).
--    2) يضيف الفهارس (بما فيها الفهارس الفريدة المهمة لمصادقة Supabase).
--    3) يحذف كل السياسات القديمة المتعفنة على الجداول الحساسة ثم يعيد إنشاء
--       مجموعة RLS صارمة (USING + WITH CHECK) لكل جدول.
--    4) ينشئ دوال مساعدة SECURITY DEFINER آمنة (private.*) لا يمكن تزوير هويتها.
--    5) ينشئ Triggers تمنع: رفع الدور، تعديل طلب فني آخر، تعديل فواتيره،
--       تعديل باركود فني آخر، وتجمّد الباركود داخل الفاتورة عند إنشائها.
--    6) ينشئ دوال الأعمال (RPC) التي يستدعيها التطبيق:
--       قبول الطلب ذرّياً، في الطريق، الإنهاء، إنشاء الفاتورة، تأكيد الدفع…
--    7) ينشئ العرض الآمن technicians_public (بدون باركود/صلاحيات/هوية).
--    8) يصلح البيانات القديمة (تطبيع الحالات، ربط tech_id في الفواتير،
--       إضافة related_id للإشعارات القديمة) — بدون حذف أي صف.
--
--  ما الذي لا يفعله (مهم جداً):
--    - لا يحذف أي مستخدم أو طلب أو فاتورة.
--    - لا يغيّر التصميم ولا يمسّ ملفات الواجهة.
--    - لا يحتوي أي مفتاح service_role أو سر FCM (الأسرار مكانها Supabase Secrets).
--    - لا يعتمد على بريد أدمن مكتوب داخل الكود؛ الأدمن = users.role = 'admin'.
--
--  قبل التشغيل: خُذ نسخة احتياطية (Supabase → Database → Backups).
--  بعد التشغيل:  نفّذ استعلامات التحقق في نهاية الملف.
-- ============================================================================

begin;

-- ============================================================================
-- 0) فحوصات بيئية سريعة
-- ============================================================================
--  ملاحظات:
--   * auth.uid() متاح تلقائياً في Supabase (schema auth).
--   * pgcrypto مطلوب فقط لتشفير كلمات المرور القديمة أثناء ترحيل الحسابات
--     القديمة. إذا لم يكن متاحاً تبقى المطابقة النصية/المشفّرة SHA-256 تعمل،
--     لذا لن يفشل الملف كله بسببه (انظر الدالة private.password_matches).
do $$
begin
  begin
    create extension if not exists "pgcrypto" with schema extensions;
  exception when others then
    begin
      create extension if not exists "pgcrypto";
    exception when others then
      raise notice 'pgcrypto غير متاح — سيتم الاعتماد على مطابقة SHA-256 للنصوص القديمة';
    end;
  end;
end $$;

-- مخطط private: دوال مساعدة داخلية (لا يُعرض عبر PostgREST)
