-- ---------- 8.6 الفني: قبول الطلب (ذرّي — يمنع السباق والاستيلاء) ----------
create or replace function public.tech_accept_order(p_order_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_tech    bigint := private.my_tech_id();
  v_ctx     jsonb  := private.my_tech_ctx();
  v_order   public.orders;
  v_name    text;
  v_phone   text;
begin
  if v_tech is null then
    raise exception 'هذه العملية للفنيين فقط' using errcode = '42501';
  end if;
  if coalesce((v_ctx ->> 'is_active')::boolean, false) = false then
    raise exception 'حسابك الفني غير مفعّل' using errcode = '42501';
  end if;
  if coalesce((v_ctx ->> 'is_available')::boolean, true) = false then
    raise exception 'أنت غير متاح حالياً — فعّل التوفر لاستقبال طلبات جديدة' using errcode = '42501';
  end if;
  if coalesce((v_ctx ->> 'update_status')::boolean, true) = false then
    raise exception 'لا تملك صلاحية تغيير حالة الطلبات' using errcode = '42501';
  end if;

  -- قفل الصف: يمنع فنيَّين من قبول نفس الطلب في نفس اللحظة
  select * into v_order from public.orders o where o.id = p_order_id for update;
  if v_order.id is null then
    raise exception 'الطلب غير موجود' using errcode = 'P0002';
  end if;
  if v_order.status <> 'pending' or coalesce(v_order.tech_id, v_order.accepted_by_tech) is not null then
    raise exception 'الطلب غير متاح أو تم قبوله من فني آخر' using errcode = 'P0001';
  end if;
  if not coalesce((v_ctx ->> 'all_governorates')::boolean, false)
     and coalesce(trim(v_order.governorate), '') <> ''
     and v_order.governorate <> (v_ctx ->> 'governorate') then
    raise exception 'الطلب خارج نطاق محافظتك' using errcode = '42501';
  end if;

  v_name  := coalesce(nullif(trim(coalesce(v_ctx ->> 'name', '')), ''), 'فني');
  v_phone := coalesce(v_ctx ->> 'phone', '');

  update public.orders
     set tech_id          = v_tech,
         accepted_by_tech = v_tech,
         tech_name        = v_name,
         tech_phone       = v_phone,
         tech_accepted_at = now(),
         status           = 'assigned',
         updated_at       = now()
   where id = v_order.id
   returning * into v_order;

  perform private.push_notification(
    v_order.user_id, 'تم تعيين فني',
    '✅ تم قبول طلبك (' || coalesce(v_order.service, '') || ') وسيتوجه إليك الفني ' || v_name || ' قريباً',
    'tech_assigned', v_order.id, v_order.id, null
  );

  return to_jsonb(v_order);
end $$;

