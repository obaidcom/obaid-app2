-- ============================================================================
--  عبيد للصيانة — خطة ترحيل المستخدمين القدامى (Legacy Users Migration Plan)
-- ============================================================================
--  الغرض:
--    توثيق تشغيلي كامل لكيفية التعامل مع الحسابات القديمة التي أُنشئت قبل
--    اعتماد Supabase Auth، أي الحسابات التي تمتلك users.pass_word (نص صريح)
--    ولا تمتلك users.auth_uid.
--
--  ⚠️ هذا الملف للتوثيق والاستعلامات التشخيصية فقط (قراءة فقط).
--     لا ينفّذ أي تعديل على البيانات، ولا يُنشئ جداول، ولا يحذف شيئاً.
--     التنفيذ الفعلي للترحيل يتم من خلال:
--       1) sql/final_auth_and_barcode_fix.sql      (الدوال الآمنة service_role)
--       2) supabase-functions/migrate-legacy-users (Edge Function)
--       3) index.html                              (شاشة "ترحيل حساب قديم")
--
--  قاعدة صارمة:
--    كلمة المرور القديمة (pass_word) لا تُصبح مصدر دخول أبداً. تُستخدم مرة
--    واحدة فقط للتحقق من ملكية الحساب القديم، ثم تُسجَّل في Supabase Auth
--    عبر الدالة الآمنة، ثم تُمسح من قاعدة البيانات نهائياً.
-- ============================================================================


-- ============================================================================
-- 1) الكشف: من هم المستخدمون القدامى؟
-- ============================================================================

-- 1.1 عدد الحسابات التي تحتاج ترحيلاً (لا تملك auth_uid)
select count(*) as legacy_users_pending
  from public.users
 where auth_uid is null;

-- 1.2 تفصيل الحسابات القديمة حسب الدور
select coalesce(role, 'user') as role,
       count(*)                as accounts,
       count(*) filter (where coalesce(pass_word, '') <> '') as with_plaintext_password,
       count(*) filter (where coalesce(email, '')     =  '') as without_email
  from public.users
 where auth_uid is null
 group by 1
 order by 2 desc;

-- 1.3 الحسابات التي يتعذّر ترحيلها أصلاً (لا بريد → لا يمكن ربطها بـ Auth)
--     هؤلاء لا يُحذفون إطلاقاً؛ يبقى صفّهم كما هو ويُطلب منهم إنشاء حساب
--     جديد بنفس البريد، ثم تُربط صفوفهم يدوياً من لوحة التحكم عند الحاجة.
select id, name, phone, role, created_at
  from public.users
 where auth_uid is null
   and coalesce(trim(email), '') = ''
 order by id;

-- 1.4 ازدواج البريد بين الحسابات القديمة (يجب معالجته قبل أي ترحيل)
select lower(trim(email)) as email, count(*) as accounts, min(id) as keep_id, max(id) as other_id
  from public.users
 where coalesce(trim(email), '') <> ''
 group by 1
having count(*) > 1
 order by 2 desc;

