-- 3.1 الفهرس الفريد لـ auth_uid: يضمن أن حساب Auth واحد لا يرتبط إلا بصف واحد
do $$
begin
  if not exists (
    select 1 from pg_indexes
     where schemaname = 'public' and indexname = 'users_auth_uid_uidx'
  ) then
    begin
      execute 'create unique index users_auth_uid_uidx on public.users(auth_uid) where auth_uid is not null';
    exception when unique_violation then
      raise notice 'يوجد auth_uid مكرر في users — نظّف التكرار ثم أعد تشغيل الملف';
    end;
  end if;
end $$;

-- 3.2 منع ازدواج البريد (بعد تنظيف التكرارات إن وُجدت)
do $$
begin
  if not exists (
    select 1 from pg_indexes where schemaname='public' and indexname='users_email_lower_uidx'
  ) then
    begin
      execute 'create unique index users_email_lower_uidx on public.users(lower(trim(email))) where coalesce(trim(email),'''') <> ''''';
      raise notice 'تم إنشاء فهرس البريد الفريد';
    exception when unique_violation then
      raise notice 'يوجد بريد مكرر في users — لم يُنشأ الفهرس الفريد (راجع تقرير التنظيف)';
    when others then
      raise notice 'تعذر إنشاء فهرس البريد الفريد: %', sqlerrm;
    end;
  end if;
end $$;

